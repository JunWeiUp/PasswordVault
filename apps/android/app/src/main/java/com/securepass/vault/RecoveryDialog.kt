package com.securepass.vault

import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import org.json.JSONObject

@Composable
internal fun RecoveryDialog(vault: VaultRepository, state: VaultState, t: (String, String) -> String, close: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var key by remember { mutableStateOf("") }
    var confirmation by remember { mutableStateOf("") }
    var password by remember { mutableStateOf("") }
    var nextPassword by remember { mutableStateOf("") }
    var nextConfirmation by remember { mutableStateOf("") }
    var enabled by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf(false) }
    var saved by remember { mutableStateOf(false) }
    var working by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf<String?>(null) }
    var file by remember { mutableStateOf<android.net.Uri?>(null) }
    var backup by remember { mutableStateOf<ByteArray?>(null) }
    val run: (suspend () -> Unit) -> Unit = { action ->
        if (!working) { working = true; message = null; scope.launch { try { action() } catch (_: Exception) { message = t("操作未完成，请检查密钥、密码或先保存草稿。", "Operation incomplete. Check the key/password or save the pending draft first.") } finally { working = false } } }
    }
    val importer = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { file = it }
    val exporter = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/octet-stream")) { uri ->
        val bytes = backup; backup = null
        if (uri != null && bytes != null) run {
            try { withContext(Dispatchers.IO) { context.contentResolver.openOutputStream(uri)?.use { it.write(bytes) } ?: error("No output") }; key = ""; message = t("应急备份已保存，请与密钥分开存放。", "Emergency backup saved. Store it separately from the key.") }
            finally { bytes.fill(0) }
        } else bytes?.fill(0)
    }
    LaunchedEffect(Unit) { if (state.unlocked) run { enabled = vault.command("recovery-status").getBoolean("enabled") } }
    DisposableEffect(Unit) { onDispose { backup?.fill(0); key = ""; confirmation = ""; password = ""; nextPassword = ""; nextConfirmation = "" } }
    AlertDialog(
        onDismissRequest = { if (!working) close() },
        title = { Text(t("离线应急恢复", "Offline recovery")) },
        text = {
            Column(Modifier.heightIn(max = 520.dp).verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Text(t("密钥和完整应急备份必须分开保存。只有密钥不能找回无备份的数据；停用或更换密钥不会撤销旧备份。", "Keep the key and complete backup separately. A key cannot retrieve data without a backup. Disabling/replacing it does not revoke old backups."))
                if (state.unlocked) {
                    Text(if (enabled) t("已启用", "Enabled") else t("未启用", "Not enabled"))
                    if (generated) {
                        Text(key)
                        TextButton(onClick = { vault.copy(key) }) { Text(t("复制密钥", "Copy key")) }
                        Input(t("再次输入完整密钥", "Confirm complete key"), confirmation, { confirmation = it }, secret = true, enabled = !working && !state.busy)
                        Row { Checkbox(saved, { saved = it }, enabled = !working && !state.busy); Text(t("已在库外保存密钥", "Key saved outside the vault")) }
                    } else if (enabled) Input(t("恢复密钥", "Recovery key"), key, { key = it }, secret = true, enabled = !working && !state.busy)
                    Input(t("当前主密码", "Current master password"), password, { password = it }, secret = true, enabled = !working && !state.busy)
                    TextButton(enabled = !working && !generated, onClick = { run { key = vault.command("recovery-generate").getString("key"); generated = true; confirmation = ""; saved = false } }) { Text(t("生成 / 更换密钥", "Generate / replace key")) }
                    if (generated) {
                        fun normalize(value: String) = value.lowercase().filter { !it.isWhitespace() && it != '-' }
                        Button(enabled = !working && saved && password.isNotEmpty() && normalize(key) == normalize(confirmation), onClick = { run {
                            vault.command("recovery-enable", JSONObject().put("key", key).put("currentPassword", password)); enabled = true; generated = false; password = ""; confirmation = ""
                            message = t("已启用，请导出应急备份。", "Enabled. Export an emergency backup now.")
                        } }) { Text(t("确认启用", "Confirm and enable")) }
                    } else if (enabled) {
                        Button(enabled = !working && key.isNotEmpty(), onClick = { run { backup = vault.command("recovery-export", JSONObject().put("key", key)).getString("content").toByteArray(); exporter.launch("PasswordVault-emergency.pvbackup") } }) { Text(t("导出应急备份", "Export emergency backup")) }
                        TextButton(enabled = !working && password.isNotEmpty(), onClick = { run { vault.command("recovery-disable", JSONObject().put("currentPassword", password)); enabled = false; key = ""; password = "" } }) { Text(t("停用密钥", "Disable key")) }
                    }
                } else {
                    if (!state.exists) TextButton(onClick = { importer.launch(arrayOf("application/octet-stream", "application/json", "text/*")) }) { Text(if (file == null) t("选择应急备份", "Choose emergency backup") else t("已选择文件，重新选择", "File selected; choose another")) }
                    Input(t("恢复密钥", "Recovery key"), key, { key = it }, secret = true, enabled = !working && !state.busy)
                    Input(t("新主密码", "New master password"), nextPassword, { nextPassword = it }, secret = true, enabled = !working && !state.busy)
                    Input(t("确认新密码", "Confirm new password"), nextConfirmation, { nextConfirmation = it }, secret = true, enabled = !working && !state.busy)
                    Button(enabled = !working && !state.busy && key.isNotEmpty() && nextPassword.isNotEmpty() && nextPassword == nextConfirmation && (state.exists || file != null), onClick = { run {
                        val archive = if (!state.exists) withContext(Dispatchers.IO) { context.contentResolver.openInputStream(file!!)?.use { val bytes = it.readRecoveryBytes(); require(bytes.size <= 64 * 1024 * 1024); bytes.toString(Charsets.UTF_8) } ?: error("No input") } else null
                        vault.recover(key, nextPassword, archive)
                        if (vault.state.value.unlocked) close()
                    } }) { Text(t("恢复", "Recover")) }
                }
                if (working || state.busy) CircularProgressIndicator()
                message?.let { Text(it) }
            }
        },
        confirmButton = { TextButton(enabled = !working && !state.busy, onClick = close) { Text(t("关闭", "Close")) } },
    )
}

private fun java.io.InputStream.readRecoveryBytes(): ByteArray {
    val output = java.io.ByteArrayOutputStream()
    val buffer = ByteArray(8192)
    while (true) {
        val count = read(buffer)
        if (count < 0) break
        require(output.size().toLong() + count <= 64L * 1024 * 1024)
        output.write(buffer, 0, count)
    }
    return output.toByteArray()
}
