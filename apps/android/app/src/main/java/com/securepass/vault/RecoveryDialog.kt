package com.securepass.vault

import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import org.json.JSONObject

@Composable
internal fun RecoveryDialog(vault: VaultRepository, state: VaultState, t: (String, String) -> String, close: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var key by remember { mutableStateOf("") }
    var confirmation by remember { mutableStateOf("") }
    var password by remember { mutableStateOf("") }
    var nextPassword by remember { mutableStateOf("") }
    var nextConfirmation by remember { mutableStateOf("") }
    var enabled by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf(false) }
    var revealKey by remember { mutableStateOf(false) }
    var confirmingKey by remember { mutableStateOf(false) }
    var confirmDisable by remember { mutableStateOf(false) }
    var saved by remember { mutableStateOf(false) }
    var working by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf<String?>(null) }
    var file by remember { mutableStateOf<android.net.Uri?>(null) }
    var backup by remember { mutableStateOf<ByteArray?>(null) }
    val run: (suspend () -> Unit) -> Unit = { action ->
        if (!working) { working = true; message = null; scope.launch { try { action() } catch (_: Exception) { message = t("操作未完成，请检查密钥、密码或先保存草稿。", "Operation incomplete. Check the key/password or save the pending draft first.") } finally { working = false } } }
    }
    val importer = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { file = it }
    val exporter = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/octet-stream")) { uri ->
        val bytes = backup; backup = null
        if (uri != null && bytes != null) run {
            try { withContext(Dispatchers.IO) { context.contentResolver.openOutputStream(uri)?.use { it.write(bytes) } ?: error("No output") }; key = ""; message = t("应急备份已保存，请与密钥分开存放。", "Emergency backup saved. Store it separately from the key.") }
            finally { bytes.fill(0) }
        } else bytes?.fill(0)
    }
    LaunchedEffect(Unit) { if (state.unlocked) run { enabled = vault.command("recovery-status").getBoolean("enabled") } }
    DisposableEffect(Unit) { onDispose { backup?.fill(0); key = ""; confirmation = ""; password = ""; nextPassword = ""; nextConfirmation = "" } }
    VaultActionSheet(
        when {
            !state.unlocked -> t("用恢复密钥重设", "Reset with recovery key")
            generated && confirmingKey -> t("确认抄写", "Confirm your copy")
            generated -> t("生成恢复密钥", "Generate recovery key")
            else -> t("恢复密钥", "Recovery key")
        },
        if (generated) t("抄写在纸上并保存在库外。下一步需重新输入完整密钥进行确认。", "Write it on paper and keep it outside the vault. Re-enter the complete key in the next step.")
        else t("恢复密钥用于忘记主密码时重设，不会替代主密码，也不会上传。", "Use the recovery key to reset a forgotten master password. It does not replace your master password and is never uploaded."),
        { if (!working && !state.busy) close() },
    ) {
                Text(t("密钥和完整应急备份必须分开保存。只有密钥不能找回无备份的数据；停用或更换密钥不会撤销旧备份。", "Keep the key and complete backup separately. A key cannot retrieve data without a backup. Disabling/replacing it does not revoke old backups."), style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                if (state.unlocked) {
                    if (!generated) LegacySection {
                        Text(if (enabled) t("恢复密钥已启用", "Recovery key enabled") else t("尚未设置恢复密钥", "Recovery key not configured"), style = MaterialTheme.typography.titleMedium)
                        Text(if (enabled) t("请把纸质副本放在安全的地方，并定期导出应急备份。", "Keep your paper copy safe and export emergency backups regularly.") else t("忘记主密码后将无法打开密码库。", "You cannot open the vault if you forget the master password."), color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                    if (generated && !confirmingKey) {
                        LegacySection {
                            Text(if (revealKey) key else "•••• •••• •••• ••••", style = MaterialTheme.typography.bodyLarge, fontFamily = androidx.compose.ui.text.font.FontFamily.Monospace)
                            TextButton(onClick = { revealKey = !revealKey }) { Text(if (revealKey) t("隐藏密钥", "Hide key") else t("显示密钥", "Show key")) }
                            TextButton(onClick = { vault.copy(key) }) { Text(t("复制密钥", "Copy key")) }
                        }
                        Button(modifier = Modifier.fillMaxWidth(), enabled = !working && !state.busy, onClick = { confirmingKey = true; revealKey = false }) { Text(t("我已抄写", "I wrote it down")) }
                    }
                    if (generated && confirmingKey) {
                        Input(t("再次输入完整密钥", "Confirm complete key"), confirmation, { confirmation = it }, secret = true, enabled = !working && !state.busy)
                        Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) { Checkbox(saved, { saved = it }, enabled = !working && !state.busy); Text(t("已在库外保存密钥", "Key saved outside the vault"), Modifier.weight(1f)) }
                        TextButton(enabled = !working, onClick = { confirmingKey = false; revealKey = false }) { Text(t("返回查看", "Back to key")) }
                    } else if (!generated && enabled) Input(t("恢复密钥", "Recovery key"), key, { key = it }, secret = true, enabled = !working && !state.busy)
                    if (!generated || confirmingKey) Input(t("当前主密码", "Current master password"), password, { password = it }, secret = true, enabled = !working && !state.busy)
                    if (!generated) Button(enabled = !working && !state.busy, onClick = { run { key = vault.command("recovery-generate").getString("key"); generated = true; revealKey = false; confirmingKey = false; confirmation = ""; saved = false } }) { Text(if (enabled) t("重新生成", "Regenerate") else t("生成恢复密钥", "Generate recovery key")) }
                    if (generated && confirmingKey) {
                        fun normalize(value: String) = value.lowercase().filter { !it.isWhitespace() && it != '-' }
                        Button(enabled = !working && saved && password.isNotEmpty() && normalize(key) == normalize(confirmation), onClick = { run {
                            vault.command("recovery-enable", JSONObject().put("key", key).put("currentPassword", password)); enabled = true; generated = false; password = ""; confirmation = ""
                            message = t("已启用，请导出应急备份。", "Enabled. Export an emergency backup now.")
                        } }) { Text(t("确认启用", "Confirm and enable")) }
                    } else if (!generated && enabled) {
                        Button(enabled = !working && key.isNotEmpty(), onClick = { run { backup = vault.command("recovery-export", JSONObject().put("key", key)).getString("content").toByteArray(); exporter.launch("PasswordVault-emergency.pvbackup") } }) { Text(t("导出应急备份", "Export emergency backup")) }
                        TextButton(enabled = !working && !state.busy && password.isNotEmpty(), onClick = { confirmDisable = true }) { Text(t("停用恢复密钥", "Disable recovery key"), color = MaterialTheme.colorScheme.error) }
                    }
                } else {
                    if (!state.exists) TextButton(onClick = { importer.launch(arrayOf("application/octet-stream", "application/json", "text/*")) }) { Text(if (file == null) t("选择应急备份", "Choose emergency backup") else t("已选择文件，重新选择", "File selected; choose another")) }
                    Input(t("恢复密钥", "Recovery key"), key, { key = it }, secret = true, enabled = !working && !state.busy)
                    Input(t("新主密码", "New master password"), nextPassword, { nextPassword = it }, secret = true, enabled = !working && !state.busy)
                    Input(t("确认新密码", "Confirm new password"), nextConfirmation, { nextConfirmation = it }, secret = true, enabled = !working && !state.busy)
                    Button(enabled = !working && !state.busy && key.isNotEmpty() && nextPassword.isNotEmpty() && nextPassword == nextConfirmation && (state.exists || file != null), onClick = { run {
                        val archive = if (!state.exists) withContext(Dispatchers.IO) { context.contentResolver.openInputStream(file!!)?.use { val bytes = it.readRecoveryBytes(); require(bytes.size <= 64 * 1024 * 1024); bytes.toString(Charsets.UTF_8) } ?: error("No input") } else null
                        vault.recover(key, nextPassword, archive)
                        if (vault.state.value.unlocked) close()
                    } }) { Text(t("重设并解锁", "Reset and unlock")) }
                }
                if (working || state.busy) LinearProgressIndicator(Modifier.fillMaxWidth())
                message?.let { Text(it, color = MaterialTheme.colorScheme.onSurfaceVariant) }
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.End) {
                    TextButton(enabled = !working && !state.busy, onClick = close) { Text(t("取消", "Cancel")) }
                }
    }
    if (confirmDisable) AlertDialog(onDismissRequest = { if (!working) confirmDisable = false },
        title = { Text(t("停用恢复密钥？", "Disable recovery key?")) },
        text = { Text(t("停用后忘记主密码将无法通过当前密钥恢复。旧应急备份仍可使用其原密钥，无法撤销。", "The current key will no longer reset this vault. Old emergency backups remain usable with their original keys and cannot be revoked.")) },
        confirmButton = { TextButton(enabled = !working && !state.busy, onClick = { run { vault.command("recovery-disable", JSONObject().put("currentPassword", password)); enabled = false; key = ""; password = ""; confirmDisable = false } }) { Text(t("停用", "Disable"), color = MaterialTheme.colorScheme.error) } },
        dismissButton = { TextButton(enabled = !working, onClick = { confirmDisable = false }) { Text(t("取消", "Cancel")) } })
}

private fun java.io.InputStream.readRecoveryBytes(): ByteArray {
    val output = java.io.ByteArrayOutputStream()
    val buffer = ByteArray(8192)
    while (true) {
        val count = read(buffer)
        if (count < 0) break
        require(output.size().toLong() + count <= 64L * 1024 * 1024)
        output.write(buffer, 0, count)
    }
    return output.toByteArray()
}
